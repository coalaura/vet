package houserules

import (
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"reflect"
	"slices"

	"golang.org/x/tools/go/analysis"
)

type sourceExpression struct {
	filename string
	line     int
	column   int
	endLine  int
	endCol   int
	kind     reflect.Type
}

func sourcePass(pass *analysis.Pass) (*analysis.Pass, error) {
	result := pass

	for index, file := range pass.Files {
		filename := cgoSourceFile(pass.Fset, file)
		if filename == "" {
			continue
		}

		source, err := parser.ParseFile(pass.Fset, filename, nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}

		if result == pass {
			copy := *pass
			copy.Files = slices.Clone(pass.Files)

			information := *pass.TypesInfo
			information.Types = maps.Clone(pass.TypesInfo.Types)
			information.Defs = maps.Clone(pass.TypesInfo.Defs)
			information.Uses = maps.Clone(pass.TypesInfo.Uses)
			information.Selections = maps.Clone(pass.TypesInfo.Selections)

			copy.TypesInfo = &information

			result = &copy
		}

		result.Files[index] = source

		if !ast.IsGenerated(source) {
			mapSourceTypes(result, file, source)
		}
	}

	return result, nil
}

func cgoSourceFile(fileSet *token.FileSet, file *ast.File) string {
	if len(file.Comments) == 0 {
		return ""
	}

	first := file.Comments[0]
	if len(first.List) != 1 || first.List[0].Text != "// Code generated by cmd/cgo; DO NOT EDIT." {
		return ""
	}

	original := fileSet.Position(file.Pos()).Filename
	compiled := fileSet.PositionFor(file.Pos(), false).Filename

	if original == compiled {
		return ""
	}

	return original
}

func mapSourceTypes(pass *analysis.Pass, compiled, source *ast.File) {
	// CGO rewrites C references and inserts function literals. Analyze the
	// original syntax, retaining type information for unchanged expressions.
	expressions := make(map[sourceExpression]ast.Expr, len(pass.TypesInfo.Types))

	ast.Inspect(source, func(node ast.Node) bool {
		expression, ok := node.(ast.Expr)
		if ok {
			expressions[expressionLocation(pass.Fset, expression)] = expression
		}

		return true
	})

	ast.Inspect(compiled, func(node ast.Node) bool {
		expression, ok := node.(ast.Expr)
		if !ok {
			return true
		}

		original := expressions[expressionLocation(pass.Fset, expression)]
		if original == nil {
			return true
		}

		information := pass.TypesInfo
		if value, ok := information.Types[expression]; ok {
			information.Types[original] = value
		}

		switch expression := expression.(type) {
		case *ast.Ident:
			identifier := original.(*ast.Ident)

			if object, ok := information.Defs[expression]; ok {
				information.Defs[identifier] = object
			}

			if object, ok := information.Uses[expression]; ok {
				information.Uses[identifier] = object
			}
		case *ast.SelectorExpr:
			if selection, ok := information.Selections[expression]; ok {
				information.Selections[original.(*ast.SelectorExpr)] = selection
			}
		}

		return true
	})
}

func expressionLocation(fileSet *token.FileSet, expression ast.Expr) sourceExpression {
	start := fileSet.Position(expression.Pos())
	end := fileSet.Position(expression.End())

	return sourceExpression{
		filename: start.Filename,
		line:     start.Line,
		column:   start.Column,
		endLine:  end.Line,
		endCol:   end.Column,
		kind:     reflect.TypeOf(expression),
	}
}
